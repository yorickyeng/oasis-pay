CREATE TABLE IF NOT EXISTS accounts (
    id text PRIMARY KEY,
    balance bigint NOT NULL CHECK (balance >= 0)
);
CREATE TABLE IF NOT EXISTS devices (
    id text PRIMARY KEY,
    role text NOT NULL UNIQUE CHECK (role IN ('terminal', 'buyer')),
    public_key bytea NOT NULL,
    certificate bytea NOT NULL,
    valid_to bigint NOT NULL,
    revoked boolean NOT NULL DEFAULT false,
    last_sequence bigint NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS payments (
    environment text NOT NULL CHECK (environment = 'sandbox'),
    terminal_id text NOT NULL REFERENCES devices(id),
    transaction_id uuid NOT NULL,
    buyer_id text NOT NULL REFERENCES devices(id),
    order_id uuid NOT NULL,
    nonce bytea NOT NULL CHECK (octet_length(nonce) = 32),
    terminal_sequence bigint NOT NULL,
    request_hash bytea NOT NULL,
    amount bigint NOT NULL CHECK (amount BETWEEN 1 AND 100000),
    status text NOT NULL CHECK (status IN ('PAID', 'DECLINED', 'CANCELLED')),
    operation_id uuid NOT NULL UNIQUE,
    result bytea NOT NULL,
    received_at timestamptz,
    fulfilled_at timestamptz,
    PRIMARY KEY (environment, terminal_id, transaction_id),
    UNIQUE (environment, terminal_id, nonce),
    UNIQUE (environment, terminal_id, terminal_sequence),
    UNIQUE (environment, terminal_id, order_id),
    CHECK (fulfilled_at IS NULL OR (received_at IS NOT NULL AND status = 'PAID'))
);
CREATE TABLE IF NOT EXISTS ledger (
    operation_id uuid PRIMARY KEY REFERENCES payments(operation_id),
    debit_account text NOT NULL REFERENCES accounts(id),
    credit_account text NOT NULL REFERENCES accounts(id),
    amount bigint NOT NULL CHECK (amount > 0),
    CHECK (debit_account <> credit_account)
);
CREATE TABLE IF NOT EXISTS outbox (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    operation_id uuid NOT NULL REFERENCES payments(operation_id),
    event text NOT NULL CHECK (event IN ('PAID', 'DECLINED', 'CANCELLED', 'RECEIVED', 'FULFILLED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (operation_id, event)
);
